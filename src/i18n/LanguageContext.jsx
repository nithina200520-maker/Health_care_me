const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try { return localStorage.getItem('carebridge-language') === 'kn' ? 'kn' : 'en'; }
    catch { return 'en'; }
  });

  useEffect(() => {
    document.documentElement.lang = language;
    try { localStorage.setItem('carebridge-language', language); } catch { /* storage is optional */ }
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (text) => language === 'kn' ? translations[text] || text : text,
  }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  return context || { language: 'en', setLanguage: () => {}, t: (text) => text };
}

